def _topics_source(model: dict) -> str:
    p = Path(model["generated_from"]) / "apps" / "shared" / "events" / "topics.py"
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _catalog(model: dict) -> dict[str, str]:
    import re

    txt = _topics_source(model)
    return {m.group(1): m.group(2) for m in re.finditer(r'"([a-z][a-z0-9_.]+)"\s*:\s*"([a-z0-9_-]+)"', txt)}


def _nervous_types(model: dict) -> list[str]:
    import re

    txt = _topics_source(model)
    m = re.search(r"NERVOUS_SYSTEM_EVENT_TYPES[^=]*=\s*\((.*?)\)", txt, re.S)
    if not m:
        return []
    return re.findall(r'"([a-z][a-z0-9_.]+)"', m.group(1))


def _compose_profiles(model: dict) -> dict[str, list[str]]:
    """service name -> profiles, read from apps/deploy/docker-compose.yml."""
    import re

    p = Path(model["generated_from"]) / "apps" / "deploy" / "docker-compose.yml"
    try:
        txt = p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {}
    try:
        import yaml  # type: ignore
    except Exception:
        return {}
    try:
        data = yaml.safe_load(txt) or {}
    except Exception:
        return {}
    out: dict[str, list[str]] = {}
    for name, svc in (data.get("services") or {}).items():
        out[name] = list((svc or {}).get("profiles") or [])
    return out


def _module_exists(model: dict, rel: str) -> bool:
    known = {m["path"] for m in model["python"]["modules"]}
    return rel in known


