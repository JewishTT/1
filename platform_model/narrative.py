def _counts(model: dict) -> dict:
    if "counts" in model:
        return model["counts"]
    g = model["import_graph"]
    return {
        "components": len(model["components"]),
        "python_modules": model["python"]["count"],
        "typescript_modules": model["typescript"]["count"],
        "rust_modules": model["rust"]["count"],
        "rust_crates": len(model["rust"]["crates"]),
        "import_edges": g["edge_count"],
        "test_files": len(model["tests"]["by_file"]),
        "test_functions": model["tests"]["total"],
        "untested_modules": model["untested_count"],
        "http_routes": sum(len(a["routes"]) for a in model["api"]),
    }


def _components_table(model: dict) -> str:
    rows = ["| Component | Python | TypeScript | Rust | Description |", "|---|---|---|---|---|"]
    rust_by_component: dict[str, int] = {}
    for m in model["rust"]["modules"]:
        parts = m["path"].split("/")
        if len(parts) >= 2 and parts[0] == "apps":
            key = parts[1]
        elif parts[0] in ("bench", "tools", "platform_model"):
            key = parts[0]
        else:
            key = "root"
        rust_by_component[key] = rust_by_component.get(key, 0) + 1
    for c in model["components"]:
        rows.append(
            f"| `{c['name']}` | {c['python_modules']} | {c['typescript_modules']} | "
            f"{rust_by_component.get(c['name'], 0)} | {c['description']} |"
        )
    return "\n".join(rows)


def _event_lanes(model: dict) -> tuple[int, int, list[str]]:
    import re

    topics = Path(model["generated_from"]) / "apps" / "shared" / "events" / "topics.py"
    try:
        txt = topics.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0, 0, []
    pairs = re.findall(r'"([a-z][a-z0-9_.]+)"\s*:\s*"([a-z0-9_-]+)"', txt)
    lanes = sorted({v for _, v in pairs})
    return len(pairs), len(lanes), lanes


def _verified_gaps_markdown(model: dict) -> str:
    """Render the machine-checked gaps registry, not hand-written prose."""
    g = model.get("gaps", {})
    if not g:
        return "_The gaps registry was not built._"
    layer_label = {
        "0": "Layer 0 — collection",
        "1": "Layer 1 — extraction/resolution",
        "2": "Layer 2 — context engine",
        "x": "cross-cutting",
    }
    out: list[str] = [
        f"Every row is a claim in `platform_model/gaps.py` tied to re-checkable evidence; "
        f"`pytest apps/shared/tests/contract/test_platform_gaps.py` fails if any open gap's "
        f"evidence stops holding. **{g.get('open', 0)}** open gaps.",
        "",
    ]
    by_layer: dict[str, list[dict]] = {}
    for gap in g.get("gaps", []):
        by_layer.setdefault(gap["layer"], []).append(gap)
    for layer in ("0", "1", "2", "x"):
        items = by_layer.get(layer)
        if not items:
            continue
        out.append(f"### {layer_label.get(layer, layer)}")
        out.append("")
        out.append("| ID | Severity | Claim | Evidence |")
        out.append("| --- | --- | --- | --- |")
        for x in sorted(items, key=lambda x: (x["severity"], x["id"])):
            ev = ", ".join(f"`{c['path']}`" for c in x["checks"])
            out.append(f"| `{x['id']}` | {x['severity']} | {x['claim']} | {ev} |")
        out.append("")
    return "\n".join(out)


